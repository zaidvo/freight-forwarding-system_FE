  doc.text(invoice.grandTotal ? invoice.grandTotal.toLocaleString() : "0", 150, y + 17);

  // Exchange rate
  doc.setFont("helvetica", "normal");
  doc.text(`Exchange Rate: 1 USD = ${invoice.exchangeRate || 1} PKR`, 15, y + 10);

  y += 28;

  // Amount in Words
  drawBox(doc, 15, y, 180, 16, "Amount in Words");
  drawWrappedText(doc, invoice.amountInWords || "—", 18, y + 10, 174);

  drawFooter(doc, 1);
  return doc.output("blob");
