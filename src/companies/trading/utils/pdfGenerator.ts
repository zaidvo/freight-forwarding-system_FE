// Helper to draw a border box
function drawBox(doc: jsPDF, x: number, y: number, w: number, h: number, title?: string) {
  doc.setDrawColor(200, 200, 200);
  doc.rect(x, y, w, h);
  if (title) {
    doc.setFillColor(245, 247, 250);
    doc.rect(x + 0.5, y + 0.5, w - 1, 6, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(70, 80, 95);
    doc.text(title.toUpperCase(), x + 3, y + 4.5);
  }
}

// Helper to wrap text inside a box
function drawWrappedText(doc: jsPDF, text: string, x: number, y: number, maxWidth: number, fontSize = 9) {
  doc.setFont("helvetica", "normal");
  doc.setFontSize(fontSize);
  doc.setTextColor(30, 41, 59);
  
  const lines = doc.splitTextToSize(text || "—", maxWidth);
  let currentY = y;
  lines.forEach((line: string) => {
    doc.text(line, x, currentY);
    currentY += fontSize * 0.45;
  });
}

// Draw page layout skeleton
function drawDocHeader(doc: jsPDF, title: string, shipment: ImportShipment, docNo?: string) {
  // Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  doc.text(title, 15, 20);

  // Divider
  doc.setDrawColor(59, 130, 246);
  doc.setLineWidth(1);
  doc.line(15, 23, 195, 23);
  doc.setLineWidth(0.2);

  // Grid
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text("Shipment Ref:", 15, 30);
  doc.text("Customer:", 75, 30);
  doc.text(docNo ? "Doc Number:" : "Expected Arrival:", 145, 30);

  doc.setFont("helvetica", "normal");
  doc.setTextColor(15, 23, 42);
  doc.text(shipment.referenceNo || "—", 38, 30);
  doc.text(shipment.customer || "—", 92, 30);
  if (docNo) {
    doc.text(docNo, 166, 30);
  } else {
    doc.text(shipment.expectedArrivalDate ? new Date(shipment.expectedArrivalDate).toLocaleDateString() : "—", 172, 30);
  }

  // Line separating header metadata
  doc.setDrawColor(226, 232, 240);
  doc.line(15, 34, 195, 34);
}

// Draw footer
function drawFooter(doc: jsPDF, pageNum: number) {
  doc.setDrawColor(226, 232, 240);
  doc.line(15, 280, 195, 280);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text("Generated by FreightERP Forwarding System", 15, 285);
  doc.text(`Page ${pageNum}`, 185, 285);
}

