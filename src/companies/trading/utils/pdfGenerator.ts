// ─── 6. DETENTION INVOICE PDF ─────────────────────────────────────
export function generateDetentionPdf(detention: DetentionInvoice, shipment: ImportShipment) {
  const doc = new jsPDF();
  drawDocHeader(doc, "Detention Invoice", shipment, detention.invoiceNo);

  let y = 40;
  drawBox(doc, 15, y, 90, 36, "Detention Periods");
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text(`Detention Start: ${detention.detentionStart || "-"}`, 18, y + 11);
  doc.text(`Detention End: ${detention.detentionEnd || "-"}`, 18, y + 18);
  doc.text(`Free Days Allowed: ${detention.freeDays || 0} Days`, 18, y + 25);
  doc.setFont("helvetica", "bold");
  doc.text(`Chargeable Days: ${detention.chargeableDays || 0} Days`, 18, y + 32);

  drawBox(doc, 105, y, 90, 36, "Charges Calculation");
  doc.setFont("helvetica", "normal");
  doc.text(`Per Day Rate: ${detention.perDayAmount || 0} ${detention.currency || "PKR"}`, 108, y + 11);
  doc.text(`Detention Total: ${detention.detentionAmount || 0} ${detention.currency || "PKR"}`, 108, y + 18);
  doc.text(`Security Deposit: ${detention.securityDeposit || 0} ${detention.currency || "PKR"}`, 108, y + 25);
  doc.setFont("helvetica", "bold");
  
  const refundText = detention.refundAmount >= 0 
    ? `Refund Amount: ${detention.refundAmount} ${detention.currency || "PKR"}`
    : `Payable Balance: ${Math.abs(detention.refundAmount)} ${detention.currency || "PKR"}`;
  doc.text(refundText, 108, y + 32);

  y += 45;

  // Containers List
  const sourceDoc = shipment.masterBL ?? shipment.houseBL;
  drawBox(doc, 15, y, 180, 50, "Containers Associated");
  doc.setFont("helvetica", "bold");
  doc.text("Container No", 18, y + 9);
  doc.text("Size", 60, y + 9);
  doc.text("Seal No", 80, y + 9);
  doc.text("Packages", 115, y + 9);
  doc.text("Gross Weight (kg)", 138, y + 9);

  doc.line(15, y + 11, 195, y + 11);
  doc.setFont("helvetica", "normal");
  let detcontY = y + 16;
  (sourceDoc?.containers || []).forEach((c, idx) => {
    if (idx < 5) {
      doc.text(c.containerNo || "-", 18, detcontY);
      doc.text(c.size || "-", 60, detcontY);
      doc.text(c.sealNo || "-", 80, detcontY);
      doc.text(String(c.packages || 0), 115, detcontY);
      doc.text(String(c.grossWeight || 0), 138, detcontY);
      detcontY += 6;
    }
  });

  y += 60;

  // Notes
  drawBox(doc, 15, y, 180, 24, "Important Remarks");
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.text("1. Detention charge calculations are based on terminal and shipping line gate reports.", 18, y + 9);
  doc.text("2. Please settle any pending payable balances within 7 working days to retrieve original security deposits.", 18, y + 16);

  drawFooter(doc, 1);
  return doc.output("blob");
}
