  doc.text("S.No", 18, y + 9);
  doc.text("Charge Name", 32, y + 9);
  doc.text("Rate (PKR)", 105, y + 9);
  doc.text("Quantity", 140, y + 9);
  doc.text("Amount (PKR)", 165, y + 9);

  doc.line(15, y + 11, 195, y + 11);
  doc.setFont("helvetica", "normal");
